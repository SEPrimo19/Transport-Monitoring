    }

    public function test_the_vehicles_and_routes_screens_link_to_the_report(): void
    {
        // Those screens need tables this fixture does not build, so the link is checked in the
        // templates themselves rather than by rendering the pages.
        foreach (['vehicles', 'routes'] as $screen) {
            $source = file_get_contents(resource_path("views/$screen/index.blade.php"));

            $this->assertStringContainsString("route('report-center.fleet')", $source, $screen);
            $this->assertStringContainsString('Generate report', $source, $screen);
        }
    }
