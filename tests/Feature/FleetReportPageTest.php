    public function test_the_csv_has_the_same_numbers_as_the_page(): void
    {
        $r = $this->seedRoute($this->orgA, 'ALN-CAL');
        DB::table('routes')->where('id', $r)->update(['duration_minutes' => 60]);
        $v = $this->seedVehicle($this->orgA, 'BUS-1', 'AAA 111');
        $this->seedVehicle($this->orgA, 'STILL', 'SSS 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v, 'route_id' => $r, 'duration_min' => 70]);
        $this->seedTrip($this->orgA, $this->anaId, 'late', ['vehicle_id' => $v, 'route_id' => $r, 'duration_min' => 70]);
        $this->actAs('org_admin', $this->orgA);

        $page = $this->get('/report-center/fleet')->assertOk();
        $rows = $this->csv($this->get('/report-center/fleet/export')->assertOk());
        $header = array_shift($rows);

        $this->assertSame('Section', $header[0]);

        $vehicle = collect($rows)->first(fn (array $x): bool => $x[0] === 'By vehicle' && $x[1] === 'BUS-1');
        $this->assertNotNull($vehicle);
        $this->assertSame((string) $page->viewData('vehicles')[0]['trips'], $vehicle[array_search('Trips', $header, true)]);

        $route = collect($rows)->first(fn (array $x): bool => $x[0] === 'By route' && $x[1] === 'ALN-CAL');
        $this->assertNotNull($route);
        $this->assertSame((string) $page->viewData('routes')[0]['trips'], $route[array_search('Trips', $header, true)]);
        $this->assertSame('10', $route[array_search('Difference (min)', $header, true)]);

        $idle = collect($rows)->first(fn (array $x): bool => $x[0] === 'Idle vehicle');
        $this->assertSame('STILL', $idle[1]);
        $this->assertSame('0', $idle[array_search('Trips', $header, true)]);
        $this->assertSame('', $idle[array_search('Hours', $header, true)], 'An idle vehicle has no measured hours: blank, not 0.');
    }

    public function test_a_vehicle_label_starting_with_an_equals_sign_is_neutralised_in_the_csv(): void
    {
        $v = $this->seedVehicle($this->orgA, '=CMD()', 'AAA 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v]);
        $this->actAs('org_admin', $this->orgA);

        $items = array_column($this->csv($this->get('/report-center/fleet/export')->assertOk()), 1);

        $this->assertContains("'=CMD()", $items);
        $this->assertNotContains('=CMD()', $items);
    }

