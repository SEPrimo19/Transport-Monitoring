    public function test_another_cooperatives_vehicles_and_trips_never_appear(): void
    {
        $mine = $this->seedVehicle($this->orgA, 'MINE-1', 'AAA 111');
        $theirs = $this->seedVehicle($this->orgB, 'THEIRS-1', 'BBB 222');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $mine]);
        $this->seedTrip($this->orgB, $this->benId, 'on_time', ['vehicle_id' => $theirs]);
        $this->seedTrip($this->orgB, $this->benId, 'on_time', ['vehicle_id' => $theirs]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/fleet')->assertOk();

        $response->assertSee('MINE-1')->assertDontSee('THEIRS-1');
        $this->assertSame(1, $response->viewData('figures')['trips']);
    }

    public function test_no_driver_name_appears_on_the_report_or_csv(): void
