<?php

namespace Tests\Feature;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Tests\Concerns\TwoCooperativeFixture;
use Tests\TestCase;

/**
 * The printable vehicles and routes report, end to end: the real controller, the real scoped
 * models and the real aggregation SQL over two cooperatives in a private in-memory SQLite
 * database. It names vehicles and routes, and must never name a driver.
 */
class FleetReportPageTest extends TestCase
{
    use TwoCooperativeFixture;

    protected function setUp(): void
    {
        parent::setUp();
        $this->setUpFixture();
    }

    protected function tearDown(): void
    {
        $this->tearDownFixture();
        parent::tearDown();
    }

    private function seedVehicle(string $org, ?string $fleet, ?string $plate, string $status = 'active'): string
    {
        $id = (string) Str::uuid();
        DB::table('vehicles')->insert([
            'id' => $id, 'organization_id' => $org, 'fleet_code' => $fleet, 'plate_number' => $plate,
            'status' => $status, 'is_active' => $status === 'active',
        ]);

        return $id;
    }

    public function test_the_report_uses_the_report_layout_and_names_the_cooperative_and_period(): void
    {
        $v = $this->seedVehicle($this->orgA, 'BUS-1', 'AAA 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v]);
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/fleet')->assertOk()
            ->assertSee('Cooperative A')
            ->assertSee('Generated by')
            ->assertSee('How these numbers are calculated')
            ->assertDontSee('bootstrap-icons', false);
    }

    public function test_an_empty_period_says_no_data_but_still_lists_idle_vehicles(): void
    {
        $this->seedVehicle($this->orgA, 'IDLE-ONE', 'III 111');
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/fleet')->assertOk()
            ->assertSee('No data for this period')
            ->assertSee('IDLE-ONE');
    }

    public function test_a_vehicle_with_trips_shows_its_hours_and_on_time(): void
    {
        $v = $this->seedVehicle($this->orgA, 'BUS-1', 'AAA 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v, 'duration_min' => 90]);
        $this->actAs('org_admin', $this->orgA);

        $row = $this->get('/report-center/fleet')->assertOk()->viewData('vehicles')[0];

        $this->assertSame('BUS-1', $row['label']);
        $this->assertSame(1.5, $row['hours']);
        $this->assertSame(100.0, $row['on_time_pct']);
    }

    public function test_distance_never_measured_is_a_dash_not_zero_km(): void
    {
        $v = $this->seedVehicle($this->orgA, 'BUS-1', 'AAA 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v, 'distance_km' => null]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/fleet')->assertOk();

        $this->assertNull($response->viewData('vehicles')[0]['distance_km']);
        $response->assertDontSee('0 km');
    }

    public function test_distance_partly_measured_says_how_many_trips(): void
    {
        $v = $this->seedVehicle($this->orgA, 'BUS-1', 'AAA 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v, 'distance_km' => 20.0]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v, 'distance_km' => null]);
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/fleet')->assertOk()->assertSee('from 1 of 2 trips');
    }

    public function test_a_deleted_vehicle_with_trips_is_one_combined_row_and_does_not_crash(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => (string) Str::uuid()]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => null]);
        $this->actAs('org_admin', $this->orgA);

        $rows = $this->get('/report-center/fleet')->assertOk()->viewData('vehicles');

        $this->assertCount(1, $rows);
        $this->assertSame('Vehicle no longer on file', $rows[0]['label']);
        $this->assertSame(2, $rows[0]['trips']);
    }

    public function test_an_active_vehicle_with_no_trips_is_idle_but_a_maintenance_one_is_not(): void
    {
        $ran = $this->seedVehicle($this->orgA, 'RAN', 'RRR 111');
        $this->seedVehicle($this->orgA, 'STILL', 'SSS 111');
        $this->seedVehicle($this->orgA, 'SHOP', 'HHH 111', 'maintenance');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $ran]);
        $this->actAs('org_admin', $this->orgA);

        $idle = $this->get('/report-center/fleet')->assertOk()->viewData('idle');

        $this->assertSame(['STILL'], array_column($idle, 'label'));
    }

    public function test_the_route_filter_narrows_the_tables_and_omits_idle_vehicles_with_a_note(): void
    {
        $r1 = $this->seedRoute($this->orgA, 'ALN-CAL');
        $r2 = $this->seedRoute($this->orgA, 'ALN-CAT');
        $v1 = $this->seedVehicle($this->orgA, 'ON-R1', 'AAA 111');
        $v2 = $this->seedVehicle($this->orgA, 'ON-R2', 'BBB 222');
        $this->seedVehicle($this->orgA, 'STILL', 'SSS 111');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v1, 'route_id' => $r1]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['vehicle_id' => $v2, 'route_id' => $r2]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/fleet?route='.$r1)->assertOk();

        $this->assertSame(['ON-R1'], array_column($response->viewData('vehicles'), 'label'));
        $this->assertSame(['ALN-CAL'], array_column($response->viewData('routes'), 'route_code'));
        $this->assertSame([], $response->viewData('idle'));
        $response->assertSee('not shown for a single route');
    }

    public function test_a_route_with_no_stored_duration_shows_dashes_not_zero(): void
    {
        $r = $this->seedRoute($this->orgA, 'ALN-CAL');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $r, 'duration_min' => 70]);
        $this->actAs('org_admin', $this->orgA);

        $row = $this->get('/report-center/fleet')->assertOk()->viewData('routes')[0];

        $this->assertNull($row['stored_duration_min']);
        $this->assertNull($row['difference_min']);
        $this->assertSame(70, $row['avg_duration_min']);
    }

    public function test_a_route_difference_is_signed(): void
    {
        $r = $this->seedRoute($this->orgA, 'ALN-CAL');
        DB::table('routes')->where('id', $r)->update(['duration_minutes' => 60]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $r, 'duration_min' => 70]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/fleet')->assertOk();

        $this->assertSame(10, $response->viewData('routes')[0]['difference_min']);
        $response->assertSee('+10 min');
    }

    public function test_on_time_is_a_dash_when_no_timetable_and_unscored_counts_show(): void
    {
        $r = $this->seedRoute($this->orgA, 'ALN-CAL');
        $v = $this->seedVehicle($this->orgA, 'BUS-1', 'AAA 111');
        $this->seedTrip($this->orgA, $this->anaId, 'no_timetable', ['route_id' => $r, 'vehicle_id' => $v]);
        $this->seedTrip($this->orgA, $this->anaId, 'no_timetable', ['route_id' => $r, 'vehicle_id' => $v]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/fleet')->assertOk();

        $this->assertNull($response->viewData('routes')[0]['on_time_pct']);
        $this->assertSame(2, $response->viewData('routes')[0]['no_timetable']);
        $this->assertNull($response->viewData('vehicles')[0]['on_time_pct']);
    }

    public function test_two_vehicles_with_the_same_fleet_code_are_two_rows_with_their_plates(): void
    {
        $a = $this->seedVehicle($this->orgA, 'BUS-1', 'XYZ 111');
