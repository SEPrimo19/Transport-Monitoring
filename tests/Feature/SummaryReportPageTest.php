<?php

namespace Tests\Feature;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Tests\Concerns\TwoCooperativeFixture;
use Tests\TestCase;

/**
 * The dashboard summary, end to end: the real controllers, scoped models and aggregation SQL
 * over two cooperatives in a private in-memory SQLite database.
 *
 * It is a board pack, so it must agree with the individual reports it summarises, and it must
 * not name a single individual.
 */
class SummaryReportPageTest extends TestCase
{
    use TwoCooperativeFixture;

    protected function setUp(): void
    {
        parent::setUp();
        $this->setUpFixture();
    }

    protected function tearDown(): void
    {
        $this->tearDownFixture();
        parent::tearDown();
    }

    private function seedVehicle(string $org, string $fleet, string $status = 'active'): string
    {
        $id = (string) Str::uuid();
        DB::table('vehicles')->insert([
            'id' => $id, 'organization_id' => $org, 'fleet_code' => $fleet, 'plate_number' => $fleet.' PLATE',
            'status' => $status, 'is_active' => $status === 'active',
        ]);

        return $id;
    }

    /** @return array<string, mixed> the value of one measure, found by area and name */
    private function measure(\Illuminate\Testing\TestResponse $response, string $area, string $measure): mixed
    {
        foreach ($response->viewData('measures') as $m) {
            if ($m['area'] === $area && $m['measure'] === $measure) {
                return $m['value'];
            }
        }

        $this->fail("No measure $area / $measure");
    }

    public function test_the_report_uses_the_report_layout_and_names_the_cooperative_and_period(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/summary')->assertOk()
            ->assertSee('Cooperative A')
            ->assertSee('Generated by')
            ->assertSee('How these numbers are calculated')
            ->assertDontSee('bootstrap-icons', false);
    }

    public function test_an_empty_period_says_no_data_and_does_not_error(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/summary')->assertOk()->assertSee('No data for this period');
    }

    public function test_on_time_is_a_dash_when_no_timetable(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'no_timetable');
        $this->seedTrip($this->orgA, $this->anaId, 'unscheduled');
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/summary')->assertOk();

        $this->assertNull($this->measure($response, 'Trips', 'On time %'));
        $this->assertNull($response->viewData('headline')[1]['value']);
        $this->assertNull($this->measure($response, 'Drivers', 'On time % (all drivers)'));
    }

    public function test_median_time_to_close_is_a_dash_and_an_empty_csv_cell_when_nothing_was_closed(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->seedReport($this->orgA, null, 'other', 'submitted');
        $this->actAs('org_admin', $this->orgA);

        $this->assertNull($this->measure($this->get('/report-center/summary')->assertOk(), 'Complaints', 'Median time to close (minutes)'));

        $rows = $this->csv($this->get('/report-center/summary/export')->assertOk());
        $median = collect($rows)->first(fn (array $r): bool => $r[1] === 'Median time to close (minutes)');

        $this->assertSame('', $median[2]);
    }

    public function test_a_route_filter_dashes_idle_vehicles_and_narrows_every_area(): void
    {
        $r1 = $this->seedRoute($this->orgA, 'ALN-CAL');
        $r2 = $this->seedRoute($this->orgA, 'ALN-CAT');
        $this->seedVehicle($this->orgA, 'STILL');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $r1]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $r2]);
        $this->seedReport($this->orgA, null, 'other', 'submitted', null, ['route_id' => $r1]);
        $this->seedReport($this->orgA, null, 'other', 'submitted', null, ['route_id' => $r2]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/summary?route='.$r1)->assertOk();

        $this->assertSame(1, $this->measure($response, 'Trips', 'Trips'));
        $this->assertSame(1, $this->measure($response, 'Complaints', 'Received'));
        $this->assertNull($this->measure($response, 'Fleet', 'Idle vehicles'));
    }

    public function test_nobody_is_named_anywhere(): void
    {
        $passenger = (string) Str::uuid();
        DB::table('profiles')->insert(['id' => $passenger, 'full_name' => 'Passenger Secretname', 'role' => 'passenger', 'organization_id' => $this->orgA]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->seedReport($this->orgA, null, 'driver_behavior', 'submitted', null, [
            'passenger_profile_id' => $passenger, 'description' => 'SECRET-DESCRIPTION-TEXT',
        ]);
        $this->actAs('org_admin', $this->orgA);

        $page = $this->get('/report-center/summary')->assertOk()->getContent();
        $csv = $this->get('/report-center/summary/export')->assertOk()->streamedContent();

        foreach (['Ana Cruz', 'Passenger Secretname', 'SECRET-DESCRIPTION-TEXT'] as $secret) {
            $this->assertStringNotContainsString($secret, $page, "$secret on the page");
            $this->assertStringNotContainsString($secret, $csv, "$secret in the CSV");
        }
    }

    public function test_the_summary_agrees_with_the_individual_reports(): void
    {
        $route = $this->seedRoute($this->orgA, 'ALN-CAL');
        $ran = $this->seedVehicle($this->orgA, 'RAN');
        $this->seedVehicle($this->orgA, 'STILL');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $route, 'vehicle_id' => $ran]);
        $this->seedTrip($this->orgA, $this->anaId, 'late', ['route_id' => $route, 'vehicle_id' => $ran]);
        $this->seedReport($this->orgA, null, 'driver_behavior', 'submitted');
        $this->seedReport($this->orgA, null, 'other', 'resolved', 'upheld', ['resolved_at' => now()->format('Y-m-d H:i:s')]);
        $this->actAs('org_admin', $this->orgA);

        $summary = $this->get('/report-center/summary')->assertOk();

        $this->assertSame(
            $this->get('/report-center/trips')->viewData('figures')['trips'],
            $this->measure($summary, 'Trips', 'Trips')
        );
        $this->assertSame(
            $this->get('/report-center/complaints')->viewData('figures')['received'],
            $this->measure($summary, 'Complaints', 'Received')
        );
        $this->assertSame(
            $this->get('/report-center/fleet')->viewData('figures')['idle_vehicles'],
            $this->measure($summary, 'Fleet', 'Idle vehicles')
        );
        $this->assertSame(
            $this->get('/report-center/drivers')->viewData('figures')['complaints'],
            $this->measure($summary, 'Drivers', 'Complaints about drivers')
        );
    }

    public function test_another_cooperatives_data_never_appears(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->seedTrip($this->orgB, $this->benId, 'on_time');
        $this->seedTrip($this->orgB, $this->benId, 'late');
        $this->seedReport($this->orgB, null, 'other');
        $this->seedVehicle($this->orgB, 'THEIRS');
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/summary')->assertOk();

        $this->assertSame(1, $this->measure($response, 'Trips', 'Trips'));
        $this->assertSame(0, $this->measure($response, 'Complaints', 'Received'));
        $this->assertSame(0, $this->measure($response, 'Fleet', 'Idle vehicles'));
        $response->assertDontSee('THEIRS');
    }

    public function test_a_super_admin_is_refused(): void
    {
        $this->actAs('super_admin', null);

        $this->get('/report-center/summary')->assertForbidden();
        $this->get('/report-center/summary/export')->assertForbidden();
    }

    public function test_an_unusable_range_says_so_on_the_report(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/summary?from=2026-10-20&to=2026-10-01')->assertOk()->assertSee('last 30 days');
    }

    public function test_the_csv_is_one_row_per_measure_with_blanks_not_zeros(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'no_timetable', ['distance_km' => null]);
        $this->actAs('org_admin', $this->orgA);

        $page = $this->get('/report-center/summary')->assertOk();
        $rows = $this->csv($this->get('/report-center/summary/export')->assertOk());
        $header = array_shift($rows);

        $this->assertSame(['Area', 'Measure', 'Value'], $header);
        $this->assertCount(count($page->viewData('measures')), $rows);

        $byMeasure = array_column($rows, 2, 1);
        $this->assertSame('', $byMeasure['Distance (km)'], 'No measured distance: blank, never 0.');
        $this->assertSame('', $byMeasure['On time %'], 'Nothing scored: blank, never 0.');
        $this->assertSame('1', $byMeasure['Trips'], 'A real count prints as itself.');
        $this->assertSame('0', $byMeasure['Received'], 'A real zero count prints as 0.');
    }

    public function test_the_csv_export_route_is_not_swallowed_by_another_route(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/summary/export')->assertOk();

        $this->assertStringContainsString('text/csv', $response->headers->get('Content-Type'));
        $this->assertStringContainsString('summary-', $response->headers->get('Content-Disposition'));
    }

    public function test_the_hub_lists_the_summary(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center')->assertOk()
            ->assertSee('/report-center/summary', false)
            ->assertSee('/report-center/summary/export', false);
    }

    public function test_the_dashboard_links_to_the_summary_for_org_admins_only(): void
    {
        // The dashboard needs tables this fixture does not build, so the link and its guard are
        // checked in the template itself rather than by rendering the page.
        $source = file_get_contents(resource_path('views/dashboard.blade.php'));

        $this->assertStringContainsString("route('report-center.summary')", $source);
        $this->assertMatchesRegularExpression('/isOrgAdmin\(\).{0,600}report-center\.summary/s', $source);
    }
}
