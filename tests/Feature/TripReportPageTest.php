<?php

namespace Tests\Feature;

use Illuminate\Support\Str;
use Tests\Concerns\TwoCooperativeFixture;
use Tests\TestCase;

/**
 * The printable trips report, end to end: the real controller, the real scoped models and the
 * real aggregation SQL over two cooperatives in a private in-memory SQLite database.
 */
class TripReportPageTest extends TestCase
{
    use TwoCooperativeFixture;

    protected function setUp(): void
    {
        parent::setUp();
        $this->setUpFixture();
    }

    protected function tearDown(): void
    {
        $this->tearDownFixture();
        parent::tearDown();
    }

    public function test_the_report_uses_the_report_layout_and_names_the_cooperative_and_period(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/trips')->assertOk()
            ->assertSee('Cooperative A')
            ->assertSee('Generated by')
            ->assertSee('How these numbers are calculated')
            ->assertDontSee('bootstrap-icons', false);
    }

    public function test_an_empty_period_says_no_data_and_does_not_error(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/trips')->assertOk()->assertSee('No data for this period');
    }

    public function test_on_time_is_a_dash_on_the_headline_and_every_row_when_nothing_was_scored(): void
    {
        $route = $this->seedRoute($this->orgA, 'ALN-CAL');
        $this->seedTrip($this->orgA, $this->anaId, 'no_timetable', ['route_id' => $route]);
        $this->seedTrip($this->orgA, $this->anaId, 'unscheduled', ['route_id' => $route]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/trips')->assertOk();

        $this->assertNull($response->viewData('figures')['on_time_pct']);
        foreach ($response->viewData('byRoute') as $row) {
            $this->assertNull($row['on_time_pct']);
        }
        foreach ($response->viewData('byPeriod') as $row) {
            $this->assertNull($row['on_time_pct']);
        }
    }

    public function test_a_deleted_route_with_trips_shows_a_dash_for_its_code(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => (string) Str::uuid()]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/trips')->assertOk();

        $this->assertSame('—', $response->viewData('byRoute')[0]['route_code']);
    }

    public function test_distance_never_measured_is_a_dash_not_zero_km(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['distance_km' => null]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/trips')->assertOk();

        $this->assertNull($response->viewData('figures')['distance_km']);
        $response->assertDontSee('0 km');
    }

    public function test_distance_measured_on_only_some_trips_says_how_many(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['distance_km' => 20.0]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['distance_km' => null]);
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/trips')->assertOk()->assertSee('from 1 of 2 trips');
    }

    public function test_the_route_filter_narrows_every_section(): void
    {
        $r1 = $this->seedRoute($this->orgA, 'ALN-CAL');
        $r2 = $this->seedRoute($this->orgA, 'ALN-CAT');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $r1]);
        $this->seedTrip($this->orgA, $this->anaId, 'late', ['route_id' => $r1]);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $r2]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/trips?route='.$r1)->assertOk();

        $this->assertSame(2, $response->viewData('figures')['trips']);
        $this->assertSame(['ALN-CAL'], array_column($response->viewData('byRoute'), 'route_code'));
        $this->assertSame(2, array_sum(array_column($response->viewData('byPeriod'), 'trips')));
    }

    public function test_a_long_period_is_bucketed_by_week_not_by_day(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->actAs('org_admin', $this->orgA);

        $from = now()->subDays(100)->format('Y-m-d');
        $to = now()->format('Y-m-d');

        $this->assertSame('week', $this->get("/report-center/trips?from=$from&to=$to")->assertOk()->viewData('granularity'));
        $this->assertSame('day', $this->get('/report-center/trips')->assertOk()->viewData('granularity'));
    }

    public function test_a_trip_just_before_midnight_lands_on_its_own_day(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['started_at' => '2026-10-05 23:59:59']);
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['started_at' => '2026-10-06 00:00:00']);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/trips?from=2026-10-01&to=2026-10-31')->assertOk();

        $this->assertSame(['2026-10-05', '2026-10-06'], array_column($response->viewData('byPeriod'), 'key'));
    }

    public function test_another_cooperatives_trips_never_appear(): void
    {
        $this->seedTrip($this->orgA, $this->anaId, 'on_time');
        $this->seedTrip($this->orgB, $this->benId, 'on_time');
        $this->seedTrip($this->orgB, $this->benId, 'late');
        $this->seedTrip($this->orgB, $this->benId, 'late');
        $this->actAs('org_admin', $this->orgA);

        $this->assertSame(1, $this->get('/report-center/trips')->assertOk()->viewData('figures')['trips']);
    }

    public function test_a_super_admin_is_refused(): void
    {
        $this->actAs('super_admin', null);

        $this->get('/report-center/trips')->assertForbidden();
        $this->get('/report-center/trips/export')->assertForbidden();
    }

    public function test_an_unusable_range_says_so_on_the_report(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/trips?from=2026-10-20&to=2026-10-01')->assertOk()->assertSee('last 30 days');
    }

    public function test_the_csv_has_the_same_rows_as_the_page_and_blank_not_zero_for_missing_values(): void
    {
        $route = $this->seedRoute($this->orgA, 'ALN-CAL');
        $this->seedTrip($this->orgA, $this->anaId, 'no_timetable', ['route_id' => $route, 'distance_km' => null]);
        $this->actAs('org_admin', $this->orgA);

        $page = $this->get('/report-center/trips')->assertOk();
        $rows = $this->csv($this->get('/report-center/trips/export')->assertOk());
        $header = array_shift($rows);

        $this->assertSame('Section', $header[0]);
        $byRoute = array_values(array_filter($rows, static fn (array $r): bool => $r[0] === 'By route'));
        $this->assertCount(count($page->viewData('byRoute')), $byRoute);
        $this->assertSame('ALN-CAL', $byRoute[0][1]);
        $this->assertSame('', $byRoute[0][array_search('On time %', $header, true)], 'No scored trip: blank, never 0.');
        $this->assertSame('', $byRoute[0][array_search('Distance (km)', $header, true)], 'No measured distance: blank, never 0.');

        $byDay = array_values(array_filter($rows, static fn (array $r): bool => $r[0] === 'By day'));
        $this->assertCount(count($page->viewData('byPeriod')), $byDay);
    }

    public function test_a_route_name_that_starts_with_an_equals_sign_is_neutralised_in_the_csv(): void
    {
        $route = $this->seedRoute($this->orgA, '=CMD()');
        $this->seedTrip($this->orgA, $this->anaId, 'on_time', ['route_id' => $route]);
        $this->actAs('org_admin', $this->orgA);

        $codes = array_column($this->csv($this->get('/report-center/trips/export')->assertOk()), 1);

        $this->assertContains("'=CMD()", $codes);
        $this->assertNotContains('=CMD()', $codes);
    }

    public function test_the_csv_export_route_is_not_swallowed_by_another_route(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/trips/export')->assertOk();

        $this->assertStringContainsString('text/csv', $response->headers->get('Content-Type'));
        $this->assertStringContainsString('trips-', $response->headers->get('Content-Disposition'));
    }

    public function test_the_hub_lists_the_trips_report(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center')->assertOk()
            ->assertSee('/report-center/trips', false)
            ->assertSee('/report-center/trips/export', false);
    }

    public function test_the_trips_screen_links_to_the_report(): void
    {
        // The Trips screen needs tables this fixture does not build, so the link is checked in the
        // template itself rather than by rendering the page.
        $source = file_get_contents(resource_path('views/trips/index.blade.php'));

        $this->assertStringContainsString("route('report-center.trips')", $source);
        $this->assertStringContainsString('Generate report', $source);
    }
}
