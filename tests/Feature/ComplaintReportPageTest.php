<?php

namespace Tests\Feature;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Tests\Concerns\TwoCooperativeFixture;
use Tests\TestCase;

/**
 * The printable complaints report, end to end: the real controller, the real scoped models and
 * two cooperatives in a private in-memory SQLite database.
 *
 * What it must never do matters as much as what it does: no complainant, no report text, no
 * vehicle and no driver appears anywhere in the page or the CSV.
 */
class ComplaintReportPageTest extends TestCase
{
    use TwoCooperativeFixture;

    protected function setUp(): void
    {
        parent::setUp();
        $this->setUpFixture();
    }

    protected function tearDown(): void
    {
        $this->tearDownFixture();
        parent::tearDown();
    }

    private function hours(int $h): string
    {
        return now()->subDays(3)->addHours($h)->format('Y-m-d H:i:s');
    }

    public function test_the_report_uses_the_report_layout_and_names_the_cooperative_and_period(): void
    {
        $this->seedReport($this->orgA, null, 'driver_behavior');
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/complaints')->assertOk()
            ->assertSee('Cooperative A')
            ->assertSee('Generated by')
            ->assertSee('How these numbers are calculated')
            ->assertDontSee('bootstrap-icons', false);
    }

    public function test_an_empty_period_says_no_data_and_does_not_error(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/complaints')->assertOk()->assertSee('No data for this period');
    }

    public function test_times_are_dashes_when_nothing_was_closed(): void
    {
        $this->seedReport($this->orgA, null, 'other', 'submitted');
        $this->seedReport($this->orgA, null, 'other', 'reviewing');
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/complaints')->assertOk();

        $this->assertNull($response->viewData('figures')['median_close_minutes']);
        $this->assertNull($response->viewData('figures')['slowest_close_minutes']);
        $response->assertDontSee('0 min');
    }

    public function test_a_resolved_report_with_no_outcome_reads_outcome_not_recorded_and_is_not_upheld(): void
    {
        $this->seedReport($this->orgA, null, 'driver_behavior', 'resolved', null, [
            'created_at' => $this->hours(0), 'resolved_at' => $this->hours(5),
        ]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/complaints')->assertOk()->assertSee('Outcome not recorded');
        $byBucket = array_column($response->viewData('byStatus'), 'count', 'bucket');

        $this->assertSame(0, $byBucket['upheld']);
        $this->assertSame(1, $byBucket['outcome_not_recorded']);
    }

    public function test_a_report_with_a_deleted_or_missing_route_is_one_combined_row(): void
    {
        $this->seedReport($this->orgA, null, 'route_issue', 'submitted', null, ['route_id' => null]);
        $this->seedReport($this->orgA, null, 'route_issue', 'submitted', null, ['route_id' => (string) Str::uuid()]);
        $this->actAs('org_admin', $this->orgA);

        $byRoute = $this->get('/report-center/complaints')->assertOk()->viewData('byRoute');

        $this->assertCount(1, $byRoute);
        $this->assertSame('Not linked to a route', $byRoute[0]['route_code']);
        $this->assertSame(2, $byRoute[0]['received']);
    }

    public function test_nothing_identifying_appears_on_the_page(): void
    {
        $this->seedIdentifyingReports();
        $this->actAs('org_admin', $this->orgA);

        $body = $this->get('/report-center/complaints')->assertOk()->getContent();

        foreach (['Passenger Secretname', 'SECRET-DESCRIPTION-TEXT', 'PLATE-SECRET', 'Ana Cruz'] as $secret) {
            $this->assertStringNotContainsString($secret, $body, "$secret must never reach the report.");
        }
    }

    public function test_the_csv_has_no_identifying_text(): void
    {
        $this->seedIdentifyingReports();
        $this->actAs('org_admin', $this->orgA);

        $body = $this->get('/report-center/complaints/export')->assertOk()->streamedContent();

        foreach (['Passenger Secretname', 'SECRET-DESCRIPTION-TEXT', 'PLATE-SECRET', 'Ana Cruz'] as $secret) {
            $this->assertStringNotContainsString($secret, $body);
        }
    }

    private function seedIdentifyingReports(): void
    {
        $passenger = (string) Str::uuid();
        DB::table('profiles')->insert(['id' => $passenger, 'full_name' => 'Passenger Secretname', 'role' => 'passenger', 'organization_id' => $this->orgA]);
        $vehicle = (string) Str::uuid();
        DB::table('vehicles')->insert(['id' => $vehicle, 'organization_id' => $this->orgA, 'plate_number' => 'PLATE-SECRET', 'is_active' => true]);

        $this->seedReport($this->orgA, null, 'driver_behavior', 'submitted', null, [
            'passenger_profile_id' => $passenger, 'description' => 'SECRET-DESCRIPTION-TEXT', 'vehicle_id' => $vehicle,
        ]);
        $this->seedReport($this->orgA, null, 'safety', 'submitted', null, [
            'passenger_profile_id' => $passenger, 'is_anonymous' => true, 'description' => 'SECRET-DESCRIPTION-TEXT',
        ]);
    }

    public function test_only_driver_conduct_is_labelled_as_about_a_driver(): void
    {
        $this->seedReport($this->orgA, null, 'driver_behavior');
        $this->actAs('org_admin', $this->orgA);

        $scope = array_column($this->get('/report-center/complaints')->assertOk()->viewData('byCategory'), 'scope', 'category');

        $this->assertSame('driver', $scope['driver_behavior']);
        $this->assertSame('safety', $scope['safety']);
        $this->assertSame('not_driver', $scope['vehicle_condition']);

        $this->get('/report-center/complaints')
            ->assertSee('Driver conduct')
            ->assertSee('Safety, shown separately')
            ->assertSee('Not about a driver');
    }

    public function test_the_route_filter_narrows_every_table(): void
    {
        $r1 = $this->seedRoute($this->orgA, 'ALN-CAL');
        $r2 = $this->seedRoute($this->orgA, 'ALN-CAT');
        $this->seedReport($this->orgA, null, 'driver_behavior', 'submitted', null, ['route_id' => $r1]);
        $this->seedReport($this->orgA, null, 'other', 'submitted', null, ['route_id' => $r1]);
        $this->seedReport($this->orgA, null, 'other', 'submitted', null, ['route_id' => $r2]);
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/complaints?route='.$r1)->assertOk();

        $this->assertSame(2, $response->viewData('figures')['received']);
        $this->assertSame(['ALN-CAL'], array_column($response->viewData('byRoute'), 'route_code'));
        $this->assertSame(2, array_sum(array_column($response->viewData('byCategory'), 'received')));
        $this->assertSame(2, array_sum(array_column($response->viewData('byStatus'), 'count')));
    }

    public function test_another_cooperatives_reports_never_appear(): void
    {
        $this->seedReport($this->orgA, null, 'other');
        $this->seedReport($this->orgB, null, 'other');
        $this->seedReport($this->orgB, null, 'other');
        $this->seedReport($this->orgB, null, 'other');
        $this->actAs('org_admin', $this->orgA);

        $this->assertSame(1, $this->get('/report-center/complaints')->assertOk()->viewData('figures')['received']);
    }

    public function test_a_super_admin_is_refused(): void
    {
        $this->actAs('super_admin', null);

        $this->get('/report-center/complaints')->assertForbidden();
        $this->get('/report-center/complaints/export')->assertForbidden();
    }

    public function test_an_unusable_range_says_so_on_the_report(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center/complaints?from=2026-10-20&to=2026-10-01')->assertOk()->assertSee('last 30 days');
    }

    public function test_the_csv_has_the_same_numbers_as_the_page(): void
    {
        $this->seedReport($this->orgA, null, 'driver_behavior', 'submitted');
        $this->seedReport($this->orgA, null, 'driver_behavior', 'resolved', 'upheld', ['resolved_at' => $this->hours(4), 'created_at' => $this->hours(0)]);
        $this->seedReport($this->orgA, null, 'other', 'dismissed', null, ['resolved_at' => $this->hours(2), 'created_at' => $this->hours(0)]);
        $this->actAs('org_admin', $this->orgA);

        $page = $this->get('/report-center/complaints')->assertOk();
        $rows = $this->csv($this->get('/report-center/complaints/export')->assertOk());
        $header = array_shift($rows);

        $this->assertSame(['Section', 'Item', 'Received', 'Closed', 'Still open', 'Scope'], $header);

        foreach ($page->viewData('byCategory') as $c) {
            $row = collect($rows)->first(fn (array $r): bool => $r[0] === 'By category' && $r[1] === $c['label']);
            $this->assertNotNull($row, $c['label']);
            $this->assertSame((string) $c['received'], $row[2], $c['label'].' received');
            $this->assertSame((string) $c['closed'], $row[3], $c['label'].' closed');
            $this->assertSame((string) $c['open'], $row[4], $c['label'].' open');
        }
        foreach ($page->viewData('byStatus') as $s) {
            $row = collect($rows)->first(fn (array $r): bool => $r[0] === 'By status' && $r[1] === $s['label']);
            $this->assertNotNull($row, $s['label']);
            $this->assertSame((string) $s['count'], $row[2], $s['label']);
        }
    }

    public function test_the_csv_export_route_is_not_swallowed_by_another_route(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $response = $this->get('/report-center/complaints/export')->assertOk();

        $this->assertStringContainsString('text/csv', $response->headers->get('Content-Type'));
        $this->assertStringContainsString('complaints-', $response->headers->get('Content-Disposition'));
    }

    public function test_the_hub_lists_the_complaints_report(): void
    {
        $this->actAs('org_admin', $this->orgA);

        $this->get('/report-center')->assertOk()
            ->assertSee('/report-center/complaints', false)
            ->assertSee('/report-center/complaints/export', false);
    }

    public function test_the_reports_screen_links_to_the_report(): void
    {
        // The Reports screen needs tables this fixture does not build, so the link is checked in
        // the template itself rather than by rendering the page.
        $source = file_get_contents(resource_path('views/reports/index.blade.php'));

        $this->assertStringContainsString("route('report-center.complaints')", $source);
        $this->assertStringContainsString('Generate report', $source);
    }
}
